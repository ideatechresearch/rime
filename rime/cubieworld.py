            proj_keep = self.V_keep @ self.V_keep.T.conj()  # (228,228) 慢投影器
            proj_fast = np.eye(self.V.shape[0]) - proj_keep  # len(self.w)
            A_fast = proj_fast @ self.A_micro @ proj_fast
            eigvals_fast = np.linalg.eigvals(A_fast)
