        sig = []
        gen = list(self.rho_slow.values())
        for _ in range(samples):
            Ug, Uh = random.sample(gen, 2)
            z_gh = Ug @ (Uh @ z)
            z_hg = Uh @ (Ug @ z)
            l2_diff = np.linalg.norm(z_gh - z_hg)  # chaos 强度
            # angle_diff = cosine_distance(z_gh, z_hg)
            sig.append(l2_diff)  # 0.7 * angle_diff + 0.3 * l2_diff
        return np.array(sig)

